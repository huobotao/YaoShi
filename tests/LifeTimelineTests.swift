import Foundation

@main struct LifeTimelineTests {
    static func main() {
        let now = Date(timeIntervalSince1970: 1_800_000_000)
        let empty = LifeTimeline(events: [], now: now)
        precondition(empty.lastFood == nil && empty.lastSleep == nil && empty.awakeSince == nil)
        let food = LifeEvent(at: now.addingTimeInterval(-49 * 3600), kind: .food, note: "一口零食")
        let sleep = LifeEvent(at: now.addingTimeInterval(-12 * 3600), kind: .sleep)
        let wake = LifeEvent(at: now.addingTimeInterval(-4 * 3600), kind: .wake)
        let future = LifeEvent(at: now.addingTimeInterval(3600), kind: .food)
        let timeline = LifeTimeline(events: [future, wake, food, sleep], now: now)
        precondition(timeline.lastFood?.id == food.id)
        precondition(now.timeIntervalSince(timeline.lastFood!.at) == 49 * 3600)
        precondition(timeline.lastSleep?.id == sleep.id && timeline.awakeSince == wake.at)
        let snack = LifeEvent(at: now.addingTimeInterval(-60), kind: .food)
        precondition(LifeTimeline(events: [food, snack], now: now).lastFood?.id == snack.id)
        let nap = LifeEvent(at: now.addingTimeInterval(-60), kind: .sleep)
        precondition(LifeTimeline(events: [wake, sleep, nap], now: now).awakeSince == nil)
        let equal = LifeEvent(at: wake.at, kind: .sleep)
        precondition(LifeTimeline(events: [wake, equal], now: now).awakeSince == nil)
        precondition(LifeTimeline(events: [sleep], now: now).awakeSince == nil)
        precondition(LifeTimeline(events: [wake], now: now).awakeSince == wake.at)
        var corrected = snack
        corrected.at = food.at.addingTimeInterval(-1)
        precondition(LifeTimeline(events: [food, corrected], now: now).lastFood?.id == food.id)
        precondition(timeline.sleeps.count == 1 && timeline.sleeps[0].duration == 8 * 3600)
        precondition(timeline.recordedSleep(since: now.addingTimeInterval(-8 * 3600)) == 4 * 3600)
        precondition(timeline.recordedSleep(since: now.addingTimeInterval(-2 * 3600)) == 0)
        precondition(timeline.events(since: sleep.at).map(\.id) == [wake.id, sleep.id])
        precondition(LifeTimeline(events: [sleep], now: now).recordedSleep(since: food.at) == 0)
        let duplicateWake = LifeEvent(at: wake.at.addingTimeInterval(60), kind: .wake)
        precondition(LifeTimeline(events: [sleep, wake, duplicateWake], now: now).sleeps.count == 1)
        let laterSleep = LifeEvent(at: sleep.at.addingTimeInterval(3600), kind: .sleep)
        precondition(LifeTimeline(events: [sleep, laterSleep, wake], now: now).sleeps[0].duration == 7 * 3600)
        let futureWake = LifeEvent(at: now.addingTimeInterval(3600), kind: .wake)
        precondition(LifeTimeline(events: [nap, futureWake], now: now).sleeps.isEmpty)
        let napWake = LifeEvent(at: now.addingTimeInterval(-30), kind: .wake)
        let multiple = LifeTimeline(events: [napWake, sleep, nap, wake], now: now)
        precondition(multiple.sleeps.count == 2)
        precondition(multiple.recordedSleep(since: food.at) == 8 * 3600 + 30)
        print("PASS: 20 life timeline checks (empty, future, multi-day, snack, wake, nap, same-time, missing wake, wake-only, correction)")
    }
}
